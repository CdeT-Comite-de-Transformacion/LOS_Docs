package cmd

import (
	"fmt"
	"github.com/spf13/cobra"
	"github.com/CdeT-Comite-de-Transformacion/LOS_Docs/starter-kit/internal/config"
	"github.com/CdeT-Comite-de-Transformacion/LOS_Docs/starter-kit/internal/generator"
)

func init() {
	var moduleName, entity string
	var force bool
	parent := &cobra.Command{Use: "usecase", Short: "Generate explicit business operations"}
	create := &cobra.Command{
		Use: "create <name>", Short: "Generate input, output and Execute in the module application layer",
		Long:    "Generate an explicit business operation. Optionally inject a CRUD entity repository with --entity.\nThe generated Execute returns a not-implemented error until business rules are added.\nA cancellation unit test and DEBUG-gated tracing are generated by default. Existing tests are preserved.\nWire the use case in module.go; no HTTP endpoint is generated automatically.",
		Example: "  modkit usecase create submit-application --module origination --entity application --dry-run",
		Args:    cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, err := config.Load(config.DefaultFilename)
			if err != nil {
				return err
			}
			gen, err := generator.New(cfg)
			if err != nil {
				return err
			}
			gen.DryRun, gen.Output = dryRun, cmd.OutOrStdout()
			if err := gen.CreateUseCase(moduleName, args[0], entity, force); err != nil {
				return err
			}
			if !dryRun {
				fmt.Fprintf(cmd.OutOrStdout(), "Created use case %q in module %q\n", args[0], moduleName)
			}
			return nil
		},
	}
	create.Flags().StringVar(&moduleName, "module", "", "existing module (required)")
	create.Flags().StringVar(&entity, "entity", "", "inject this entity's repository")
	create.Flags().BoolVar(&force, "force", false, "overwrite this use case file")
	_ = create.MarkFlagRequired("module")
	parent.AddCommand(create)
	rootCmd.AddCommand(parent)
}
